// Document model. Plain JSON, all lengths in millimetres, y pointing down.
// See docs/ARCHITECTURE.md §3. This module must not import Paper.js, React or any store.

import type { LengthUnit } from '../lib/units'
import type { Vec2 } from '../lib/vec2'

export type Id = string

export type LayerKind = 'cut' | 'stitch' | 'reference' | 'notes'
export type LineStyle = 'solid' | 'dashed' | 'dotted' | 'dashDot'
export type JoinStyle = 'round' | 'miter' | 'bevel'
export type HoleShape = 'round' | 'slit'
export type CornerMode = 'fixed' | 'cornerAware'

export interface Layer {
  id: Id
  name: string
  kind: LayerKind
  visible: boolean
  locked: boolean
  color: string
}

interface EntityBase {
  id: Id
  layerId: Id
  lineStyle: LineStyle
  /** Export stroke width in mm. On screen strokes are hairlines. */
  strokeWidth: number
}

/** Same shape as paper.Segment: anchor plus handles relative to the anchor. */
export interface Segment {
  p: Vec2
  hi?: Vec2
  ho?: Vec2
}

/**
 * A path that follows another entity at a fixed offset (a stitch line). Regenerated whenever the source
 * changes; see src/document/derived.ts.
 */
export interface OffsetDerivation {
  kind: 'offset'
  sourceId: Id
  /** Signed offset in mm: for closed sources negative is inward (offsetEntity's convention). */
  margin: number
  join: JoinStyle
}

export interface PathEntity extends EntityBase {
  type: 'path'
  segments: Segment[]
  closed: boolean
  derived?: OffsetDerivation
}

export interface CircleEntity extends EntityBase {
  type: 'circle'
  center: Vec2
  rx: number
  ry: number
  /** Degrees, clockwise (y-down). */
  rotation: number
}

export interface TextEntity extends EntityBase {
  type: 'text'
  position: Vec2
  text: string
  /** Font size in mm. */
  size: number
  rotation: number
}

export interface CentreLineEntity extends EntityBase {
  type: 'centreLine'
  from: Vec2
  to: Vec2
}

export interface HoleSetEntity extends EntityBase {
  type: 'holeSet'
  /** The line the holes follow (usually a stitch line). null = detached: the holes are fixed. */
  sourceEntityId: Id | null
  /** Signed offset from the source before distributing (offsetEntity's convention); usually 0. */
  margin: number
  pitch: number
  holeShape: HoleShape
  /** Diameter for round holes, slit length for slits (mm). */
  holeSize: number
  /** Slit angle in degrees relative to the path tangent. */
  slitAngle: number
  cornerMode: CornerMode
  /** Cached output of the distribution algorithm; regenerated by the derivation pass. */
  holes: Vec2[]
  /** Cached path direction at each hole, degrees clockwise (y-down), parallel to `holes`. Slits use it. */
  angles?: number[]
}

export type Entity = PathEntity | CircleEntity | TextEntity | CentreLineEntity | HoleSetEntity
export type EntityType = Entity['type']

export interface Piece {
  id: Id
  name: string
  quantity: number
  mirrored: boolean
  entities: Entity[]
}

export interface ProjectSettings {
  stitchMargin: number
  pitch: number
  holeSize: number
}

export interface Project {
  schemaVersion: number
  id: Id
  name: string
  displayUnit: LengthUnit
  settings: ProjectSettings
  layers: Layer[]
  pieces: Piece[]
}

export const PITCH_PRESETS_MM = [2.7, 3.0, 3.38, 3.85, 4.0] as const

export const LINE_DASH_MM: Record<LineStyle, number[] | null> = {
  solid: null,
  dashed: [3, 1.5],
  dotted: [0.3, 1.2],
  dashDot: [6, 1.5, 0.5, 1.5],
}
